"""Паспортные сведения единицы оборудования ГРП: поля, подписи, порядок граф.

Одно описание на трёх потребителей сразу — раскладку колонок в базе, графы
таблицы «Оборудование» и поля формы ввода единицы. Иначе подписи и порядок
разъезжаются: графа в таблице есть, а ввести в неё нечего.

Сведения хранятся текстом, как и раздел 1 паспорта ГРП: изготовитель, ДУ и
примечание — свободные строки, а числа паспорта (назначенный срок службы,
назначенная и фактическая наработка) переносятся так, как написаны в
документации, и ни в каком расчёте не участвуют.

Особый случай — назначенный срок службы. Документация назначает его не
всегда: вместо числа лет в паспорте пишут «не нормируется». Тогда и
фактическую наработку показывать не с чем сравнивать — в таблице у такой
единицы стоит прочерк (см. NOT_NORMED и table_cells).
"""
import re
from typing import Dict, Sequence

from core.timefmt import DurationError, parse_years

EMPTY = '—'

# «Срок не назначен»: в графе «Назначенный срок службы, лет» стоит не число,
# а слова. Это не произвольный текст, а значение поля: от него зависит показ
# фактической наработки, поэтому написания сводятся к одному (norm_life), а
# ввод проверяется (parse_life).
NOT_NORMED = 'не нормируется'

# Написания, которые считаются тем же значением: регистр, «ё», лишние пробелы
# и точка в конце не различаются (см. is_not_normed).
_NOT_NORMED_FORMS = frozenset((
    'не нормируется', 'не нормирован', 'не нормировано', 'не нормируются',
    'ненормируется', 'ненормирован', 'ненормировано',
))

# Графы таблицы оборудования: (ключ, подпись, ширина). Первой идёт графа
# «№» — номер строки, он нигде не хранится: это место единицы в списке.
TABLE_COLUMNS = (
    ('name', 'Наименование оборудования', 250),
    ('model', 'Тип (модель)', 140),
    ('manufacturer', 'Изготовитель', 130),
    ('dn', 'Диаметр условный ДУ', 120),
    ('quantity', 'Кол-во, шт.', 80),
    ('scheme_number', 'Номер по схеме', 110),
    ('install_date', 'Дата монтажа (установки)', 120),
    ('assigned_life', 'Назначенный срок службы, лет', 130),
    ('assigned_hours', 'Назначенная наработка', 120),
    ('actual_hours', 'Фактическая наработка', 120),
    ('note', 'Примечание', 200),
)

# Сведения, которых нет в прежней таблице equipment: добавляются колонками
# в конец, поэтому прежние поля сохраняют свои индексы.
DETAIL_COLUMNS = ('model', 'manufacturer', 'dn', 'quantity', 'scheme_number',
                  'assigned_life', 'assigned_hours', 'actual_hours', 'note')

# Колонки строки выборки get_equipment_by_grp: id и четыре прежних поля идут
# первыми — по их индексам читают расчёт, отчёт и интерфейс.
ROW_COLUMNS = ('id', 'name', 'install_date', 'removal_date') + DETAIL_COLUMNS

# Поля формы ввода: (ключ, подпись, подсказка). Даты снятия здесь нет: её
# ставит само приложение, когда единицу заменяют целиком (removal_date в базе
# остаётся — по нему расчёт отличает снятое оборудование от действующего).
FORM_FIELDS = (
    ('name', 'Наименование оборудования', 'как в каталоге — по нему подтянутся запчасти'),
    ('model', 'Тип (модель)', 'например: КРОН-150'),
    ('manufacturer', 'Изготовитель', 'завод-изготовитель по паспорту'),
    ('dn', 'Диаметр условный ДУ', 'например: 50'),
    ('quantity', 'Кол-во, шт.', 'сколько таких единиц стоит в ГРП'),
    ('scheme_number', 'Номер по схеме', 'позиция по технологической схеме'),
    ('install_date', 'Дата монтажа (установки)', 'от неё считается срок службы запчастей'),
    ('assigned_life', 'Назначенный срок службы, лет',
     'число лет по документации изготовителя либо «не нормируется»'),
    ('assigned_hours', 'Назначенная наработка', 'по документации, в часах'),
    ('actual_hours', 'Фактическая наработка',
     'наработка с начала эксплуатации; прочерк при «не нормируется»'),
    ('note', 'Примечание', 'свободная строка'),
)


def _flat(text) -> str:
    """Строка для сравнения написаний: без краевых пробелов, «ё» → «е», нижний регистр."""
    return ' '.join(str(text or '').split()).replace('ё', 'е').replace('Ё', 'Е').lower()


def is_not_normed(text) -> bool:
    """Срок не назначен: в графе срока написано «не нормируется», а не число лет.

    Различаются только слова, а не их написание: «Не нормируется.», «НЕ
    НОРМИРУЕТСЯ», «ненормируется» — одно и то же значение.
    """
    return _flat(text).rstrip('.') in _NOT_NORMED_FORMS


def norm_life(text) -> str:
    """Графа срока в едином написании: «не нормируется» либо текст как введён.

    Без приведения у одинаковых по смыслу единиц в таблице стояли бы разные
    записи («Не нормируется», «не нормирован»), а правило «фактическая
    наработка — прочерк» срабатывало бы не у всех.
    """
    return NOT_NORMED if is_not_normed(text) else str(text or '').strip()


def parse_life(text) -> str:
    """Проверить графу «Назначенный срок службы, лет» и вернуть её значение.

    Допустимо пустое значение, число лет («20», «20 лет», «20 лет 6 мес») и
    слова «не нормируется». Всё прочее — DurationError с понятным текстом:
    графа попадает в паспорт, и «20 лет, продлён» в ней неотличимо от описки.
    """
    value = str(text or '').strip()
    if not value:
        return ''
    if is_not_normed(value):
        return NOT_NORMED
    if parse_years(value) is None:
        raise DurationError(
            'Назначенный срок службы — число лет (например, «20») '
            'либо «не нормируется».')
    return value


def _name_key(text) -> str:
    """Написание, по которому узнают одну и ту же модель.

    Различаются только написания: регистр, «ё», лишние пробелы и пробелы
    вокруг дефиса — «РДС-32», «рдс-32» и «РДС  -  32» это одна модель.
    """
    return re.sub(r'\s*-\s*', '-', _flat(text))


def same_name(first, second) -> bool:
    """Одно и то же наименование оборудования?

    Пустое наименование ничему не равно — иначе пустая строка «совпала» бы
    с каждой незаполненной записью.
    """
    left = _name_key(first)
    return bool(left) and left == _name_key(second)


def find_by_name(rows: Sequence, name) -> Sequence:
    """Строка выборки с тем же наименованием — либо None.

    Ищет по графе «Наименование оборудования» (см. ROW_COLUMNS), поэтому
    годится и для проверки «такая единица уже есть», и для поиска образца в
    каталоге. Читается тем же способом, что и остальные графы, — по имени
    поля, а не по номеру.
    """
    wanted = _name_key(name)
    if not wanted:
        return None
    for row in rows:
        if _name_key(value(row, 'name')) == wanted:
            return row
    return None


def value(row: Sequence, key: str) -> str:
    """Значение поля из строки выборки; '' — если поля в строке нет.

    Индекс считается по ROW_COLUMNS, а не пишется числом: при добавлении
    колонки в конец здесь ничего менять не нужно. Короткая строка (защитный
    запасной кортеж в вызывающем коде) не роняет чтение — поле пустое.
    """
    try:
        index = ROW_COLUMNS.index(key)
    except ValueError:
        return ''
    try:
        return row[index] or ''
    except IndexError:
        return ''


def values(row: Sequence) -> Dict[str, str]:
    """Все паспортные сведения строки: {ключ: значение} — пустое остаётся ''.

    Значения обрезаются по краям: форма сохраняет их уже обрезанными, и
    сравнение «до/после» не должно видеть разницы там, где её нет.
    Назначенный срок приводится к единому написанию (norm_life).
    """
    result = {key: str(value(row, key)).strip() for key in DETAIL_COLUMNS}
    result['assigned_life'] = norm_life(result['assigned_life'])
    return result


def details(source: Dict) -> Dict[str, str]:
    """Паспортные сведения из словаря формы: {ключ: строка}, пустое — ''."""
    result = {key: str(source.get(key) or '').strip() for key in DETAIL_COLUMNS}
    result['assigned_life'] = norm_life(result['assigned_life'])
    return result


def form_item(row: Sequence) -> Dict:
    """Единица оборудования для формы правки: id, даты и паспортные сведения.

    Ключи те же, что у полей формы, — по ним список в форме и заполняется.
    """
    return {'id': row[0], 'name': row[1], 'install_date': row[2] or '',
            'removal_date': row[3] or '', **values(row)}


def table_cells(item: Dict) -> list:
    """Значения граф таблицы по словарю единицы (список оборудования в форме ГРП).

    Словарь — тот же, что у формы и у списка: ключи TABLE_COLUMNS. У единицы с
    неназначенным сроком службы фактическая наработка показывается прочерком:
    срок не нормирован, сравнивать наработку не с чем.
    """
    data = {key: str(item.get(key) or '').strip()
            for key, _label, _width in TABLE_COLUMNS}
    data['assigned_life'] = norm_life(data['assigned_life'])
    if is_not_normed(data['assigned_life']):
        data['actual_hours'] = ''
    return [data[key] or EMPTY for key, _label, _width in TABLE_COLUMNS]


def table_view(row: Sequence) -> list:
    """Значения граф таблицы оборудования в порядке TABLE_COLUMNS.

    Строка выборки превращается в словарь по TABLE_COLUMNS и показывается так
    же, как список в форме (table_cells) — иначе правило «не нормируется»
    работало бы на одном экране и не работало на другом.
    """
    return table_cells({key: value(row, key)
                        for key, _label, _width in TABLE_COLUMNS})


def table_index(key: str) -> int:
    """Номер значения графы в строке таблицы.

    Первой графой идёт «№», поэтому к позиции в TABLE_COLUMNS прибавляется
    единица. Индекс считается, а не пишется числом: при перестановке граф
    чтение строки не сломается.
    """
    return 1 + [column for column, _label, _width in TABLE_COLUMNS].index(key)
