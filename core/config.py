# Нормативный срок полной проверки оборудования ГРП, лет.
# По правилу отрасли срок службы элемента ГРП составляет 5 лет либо 20 лет:
# по истечении 20 лет проводится полная проверка оборудования, и эксплуатация
# не подтверждается. Применяется в отчёте там, где нормативный срок в базе
# не задан; сам расчёт методики при этом не изменяется.
FULL_CHECK_TERM = 20.0

# Срок службы заменяемых деталей (мембрана, пружина, седло клапана и т.п.), лет.
# Срок 5 лет имеют только детали, помеченные признаком is_replaceable.
REPLACEABLE_NORM_YEARS = 5.0


def part_norm(is_replaceable: bool) -> float:
    """Нормативный срок службы детали по признаку заменяемости.

    Заменяемая деталь — 5 лет, всё остальное оборудование и комплектующие —
    срок полной проверки (20 лет).
    """
    return REPLACEABLE_NORM_YEARS if is_replaceable else FULL_CHECK_TERM

